// Helper functions for career data management
const CareerDataManager = {
  // Get all active career listings
  getAllActiveCareers: function() {
    return careerData.filter(career => career.isActive);
  },

  // Get career by ID
  getCareerById: function(id) {
    return careerData.find(career => career.id === id);
  },

  // Get careers by category
  getCareersByCategory: function(category) {
    return careerData.filter(career => career.category === category && career.isActive);
  },

  // Get careers by location
  getCareersByLocation: function(location) {
    return careerData.filter(career => career.location === location && career.isActive);
  },

  // Get careers by type
  getCareersByType: function(type) {
    return careerData.filter(career => career.type === type && career.isActive);
  },

  // Get all unique categories
  getCategories: function() {
    const categories = [...new Set(careerData.map(career => career.category))];
    return categories;
  },

  // Get all unique locations
  getLocations: function() {
    const locations = [...new Set(careerData.map(career => career.location))];
    return locations;
  },

  // Get all unique job types
  getJobTypes: function() {
    const types = [...new Set(careerData.map(career => career.type))];
    return types;
  },

  // Search careers by keyword
  searchCareers: function(keyword) {
    const searchTerm = keyword.toLowerCase();
    return careerData.filter(career => 
      career.isActive && (
        career.title.toLowerCase().includes(searchTerm) ||
        career.description.toLowerCase().includes(searchTerm) ||
        career.shortDescription.toLowerCase().includes(searchTerm) ||
        career.category.toLowerCase().includes(searchTerm)
      )
    );
  }
};
